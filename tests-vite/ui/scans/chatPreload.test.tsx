import '@testing-library/jest-dom/vitest';
import './mockChatEditor';
import { QueryClient } from '@tanstack/react-query';
import { act, cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react';
import { afterEach, beforeEach, expect, it } from 'vitest';
import { ScanChatWidget } from '@/features/scans/ScanChatWidget';
import { transitionScanSession, scanSession } from '@/shared/api/auth/scanSession';
import { createChatClient } from '@/shared/api/scans/llmChatClient';
import { chatApi, sourceTransport, status } from './llmChatFixtures';
beforeEach(() => transitionScanSession('preload-owner', new QueryClient(), true));
afterEach(cleanup);
it('preloads history before opening, shows skeleton then empty state and never generates on mount', async () => {
  const api = chatApi();
  let release!: () => void;
  const gate = new Promise<void>(resolve => { release = resolve; });
  const fetcher: typeof fetch = async (...args) => { await gate; return api.fetcher(...args); };
  const { container } = render(<ScanChatWidget status={status} transport={sourceTransport()} client={createChatClient(scanSession(), fetcher)} />);
  expect(document.querySelector('.scan-chat-skeleton')).toBeInTheDocument();
  fireEvent.click(screen.getByRole('button', { name: 'Открыть чат по отчёту' }));
  expect(screen.queryByRole('button', { name: /Отменить|Обновить историю/ })).toBeNull();
  await act(async () => release());
  await screen.findByRole('heading', { name: 'Напишите первое сообщение' });
  expect(document.querySelector('.scan-chat-skeleton')).toBeNull();
  const send = screen.getByRole('button', { name: 'Отправить вопрос' });
  expect(send).toBeDisabled();
  expect(send.closest('.scan-chat-compose-field')).not.toBeNull();
  expect(send).toHaveTextContent('');
  expect(api.requests.every(request => request.init.method === 'GET')).toBe(true);
  expect(container).toBeTruthy();
});
it('finishes the background read while the dialog stays closed', async () => {
  const api = chatApi();
  render(<ScanChatWidget status={status} transport={sourceTransport()} client={createChatClient(scanSession(), api.fetcher)} />);
  await waitFor(() => expect(api.requests.filter(request => request.path.endsWith('/chat/context'))).toHaveLength(2));
  expect(screen.queryByRole('dialog')).toBeNull();
  expect(api.requests.every(request => request.init.method === 'GET')).toBe(true);
  fireEvent.click(screen.getByRole('button', { name: 'Открыть чат по отчёту' }));
  await screen.findByRole('heading', { name: 'Напишите первое сообщение' });
});
