for (const mode of ['capped', 'uncapped']) for (const operations of [false, true]) {
  test(`absent lifetime cap preserves legacy ${mode}, operations=${operations} bytes/hash`, async () => {
    const input = descriptor(mode, operations), before = structuredClone(input);
    const output = validateOpenAiDeployment(input);
    assert.deepEqual(input, before);
    assert.deepEqual(output, input);
    assert.equal(Object.hasOwn(output.environment, FIELD), false);
    assert.ok(Object.isFrozen(output) && Object.isFrozen(output.environment));
    assert.equal(hash(output), legacyHashes[mode][Number(operations)]);
    assert.equal(await normalize(input), JSON.stringify(output));
    for (const key of Object.keys(input.environment)) {
      const missing = structuredClone(input); delete missing.environment[key];
      assert.throws(() => validateOpenAiDeployment(missing), HOLD);
    }
  });
}

test('optional uncapped lifetime micros accepts 5 USD and backend integer range endpoints only as strings', async () => {
  assert.equal(facadeValidate, validateOpenAiDeployment);
  for (const value of ['1', '5000000', '1000000000']) {
    const input = withLifetime(value), before = structuredClone(input);
    const output = validateOpenAiDeployment(input);
    assert.deepEqual(input, before);
    assert.deepEqual(output, input);
    assert.equal(output.environment[FIELD], value);
    assert.deepEqual(Object.keys(output.environment), Object.keys(output.environment).sort());
    assert.equal(await normalize(input), JSON.stringify(output));
    const without = structuredClone(output); delete without.environment[FIELD];
    assert.deepEqual(without, validateOpenAiDeployment(descriptor()));
    assert.notEqual(hash(output), hash(without));
    assert.equal(output.monetaryLimit, 'uncapped');
    assert.equal(output.environment.OPENAI_MONETARY_LIMIT, 'uncapped');
    assert.equal(output.environment.LLM_QUOTA_MONETARY_LIMIT, 'uncapped');
  }
  const inactive = withLifetime(); inactive.environment.OPENAI_ENABLED = 'false'; inactive.credentialVolume = null;
  assert.deepEqual(validateOpenAiDeployment(inactive), inactive);
});

